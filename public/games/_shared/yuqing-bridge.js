  // The LittleJS engine loader uses this for canvas HUD text. Other ports can
  // ignore it; exposing one small pure function keeps the bridge reusable.
  window.yuqingTranslateText = translateValue;

  function translateElement(element) {
    for (const attribute of ["placeholder", "aria-label", "title", "alt", "data-hint"]) {
      const value = element.getAttribute(attribute);
      if (!value) continue;
      const translated = translateValue(value);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  }

  function translateTree(root) {
    if (root.nodeType === Node.TEXT_NODE) {
      const parent = root.parentElement;
      if (!parent || skipTags.has(parent.tagName)) return;
      const translated = translateValue(root.nodeValue ?? "");
      if (translated !== root.nodeValue) root.nodeValue = translated;
      return;
    }
    if (!(root instanceof Element || root instanceof Document || root instanceof DocumentFragment)) return;
    if (root instanceof Element) translateElement(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) {
        const parent = node.parentElement;
        if (parent && !skipTags.has(parent.tagName)) {
          const translated = translateValue(node.nodeValue ?? "");
          if (translated !== node.nodeValue) node.nodeValue = translated;
        }
      } else if (node instanceof Element) {
        translateElement(node);
      }
      node = walker.nextNode();
    }
  }

